"""``crm.api.comment.add_comment`` - Group C. Ported from ``crm/api/comment.py``.

Mention extraction is ported too, because it is what produces the Mention notifications
the bell menu shows. It is not a whitelisted endpoint upstream - it hangs off the
Comment ``on_update`` hook - but it lives here because that is where the source puts it.
"""

from __future__ import annotations

import re

from frappe_core import doc_caches, permissions, registry
from frappe_core.exceptions import DoesNotExistError
from frappe_core.exceptions import PermissionError as FrappePermissionError
from frappe_core.query import parse_json_param
from frappe_core.session import get_current_user
from frappe_core.whitelist import whitelist

#: ``crm/api/comment.py:60-66`` parses ``<span data-type="mention" data-id="..." ...>``
#: with BeautifulSoup. A regex is used here rather than adding a parser dependency; the
#: markup is generated by the editor, not hand-written, so its shape is fixed. Both
#: attribute orders are accepted because the editor is not guaranteed to emit them in
#: a stable order.
_MENTION_SPAN = re.compile(
    r"<span[^>]*data-type=[\"']mention[\"'][^>]*>", re.IGNORECASE
)
_DATA_ID = re.compile(r"data-id=[\"']([^\"']+)[\"']", re.IGNORECASE)
_DATA_LABEL = re.compile(r"data-label=[\"']([^\"']*)[\"']", re.IGNORECASE)


def extract_mentions(html: str) -> list[dict]:
    """``crm/api/comment.py:57-66``. Returns ``[{"full_name", "email"}, ...]``."""
    if not html:
        return []
    mentions = []
    for span in _MENTION_SPAN.findall(html):
        email = _DATA_ID.search(span)
        if not email:
            continue
        label = _DATA_LABEL.search(span)
        mentions.append(
            {"full_name": label.group(1) if label else "", "email": email.group(1)}
        )
    return mentions


def notify_mentions(comment) -> None:
    """``crm/api/comment.py:23-54``.

    The notification text is HTML assembled upstream with the mentioning user's name,
    the doctype word (``CRM Lead`` -> ``lead``) and the record's display name. Kept
    byte-for-byte in shape because the frontend renders it as HTML.
    """
    from crm_app.models import CRMNotification
    from frappe_platform.models import User

    content = getattr(comment, "content", None)
    if not content or not comment.reference_doctype or not comment.reference_name:
        return
    mentions = extract_mentions(content)
    if not mentions:
        return
    if not registry.has_doctype(comment.reference_doctype):
        return

    reference = (
        registry.get_model(comment.reference_doctype)
        ._default_manager.filter(pk=comment.reference_name)
        .first()
    )
    if reference is None:
        return

    doctype_word = comment.reference_doctype
    if doctype_word.startswith("CRM "):
        doctype_word = doctype_word[4:].lower()

    if doctype_word == "lead":
        display = getattr(reference, "lead_name", "") or ""
    else:
        display = getattr(reference, "organization_id", None) or getattr(
            reference, "lead_name", ""
        ) or ""

    owner_full_name = (
        User._default_manager.filter(pk=comment.owner_id).values_list("full_name", flat=True).first()
        or comment.owner_id
    )

    notification_text = (
        '\n            <div class="mb-2 leading-5 text-ink-gray-5">\n'
        f'                <span class="font-medium text-ink-gray-9">{owner_full_name}</span>\n'
        f"                <span>mentioned you in {doctype_word}</span>\n"
        f'                <span class="font-medium text-ink-gray-9">{display}</span>\n'
        "            </div>\n        "
    )

    for mention in mentions:
        # crm_notification.notify_user:340 - never notify yourself.
        if mention["email"] == comment.owner_id:
            continue
        if not User._default_manager.filter(pk=mention["email"]).exists():
            continue
        CRMNotification._default_manager.create(
            from_user_id=comment.owner_id,
            to_user_id=mention["email"],
            type="Mention",
            message=comment.content,
            notification_text=notification_text,
            notification_type_doctype="Comment",
            notification_type_doc=str(comment.pk),
            reference_doctype=comment.reference_doctype,
            reference_name=str(comment.reference_name),
        )


@whitelist("crm.api.comment.add_comment")
def add_comment(
    reference_doctype: str,
    reference_name: str,
    content: str,
    attachments: str | list | None = None,
):
    """``crm/api/comment.py:69-90``.

    Upstream delegates to ``frappe.desk.form.utils.add_comment``, which checks write
    permission on the *referenced* document before creating the Comment. That check is
    reproduced here - without it any authenticated user could comment on a lead they
    cannot see, and the comment would then appear in that lead's timeline.
    """
    from frappe_platform.models import Comment, User

    # Upstream reaches frappe.get_doc(reference_doctype, reference_name), which raises
    # DoesNotExistError - a 404, not a validation failure (FINDINGS.md 12).
    if not registry.has_doctype(reference_doctype):
        raise DoesNotExistError(f"DocType {reference_doctype} not found")

    reference = (
        registry.get_model(reference_doctype)._default_manager.filter(pk=reference_name).first()
    )
    if reference is None:
        raise DoesNotExistError(f"{reference_doctype} {reference_name} not found")

    user = get_current_user()
    if not permissions.check_object_permission(reference, "write", user):
        raise FrappePermissionError(f"No permission for {reference_doctype} {reference_name}")

    full_name = (
        User._default_manager.filter(pk=user).values_list("full_name", flat=True).first() or user
    )

    comment = Comment._default_manager.create(
        comment_type="Comment",
        reference_doctype=reference_doctype,
        reference_name=str(reference_name),
        content=content,
        comment_email=user,
        comment_by=full_name,
    )

    parsed = parse_json_param(attachments, []) or []
    if parsed:
        _add_attachments(comment, parsed)

    notify_mentions(comment)
    # The `_comments` cache follows Comment writes by signal, but the mention pass and
    # attachments happen after; refresh so the response reflects the final state.
    doc_caches.rebuild_comment_cache(reference_doctype, str(reference_name))

    return registry.get_entry("Comment").get_serializer_class()(comment).data


def _add_attachments(comment, attachments) -> None:
    """``crm/api/comment.py:93-126``.

    Upstream accepts either a File name or a ``{"fname", "fcontent"}`` dict from
    ``frappe.attach_print``. Only the first form is reachable from the frontend; the
    second, a rendered print, has no producer here and is skipped. (Storing bytes is
    ``File._content`` + ``save()`` since FINDINGS.md 49; the gap is the print, not the
    storage.)
    """
    from frappe_platform.models import File

    for attachment in attachments:
        if not isinstance(attachment, str):
            continue
        source = File._default_manager.filter(pk=attachment).first()
        if source is None:
            continue
        File._default_manager.create(
            file_url=source.file_url,
            file_name=source.file_name,
            is_private=source.is_private,
            attached_to_doctype="Comment",
            attached_to_name=str(comment.pk),
            folder="Home/Attachments",
        )
